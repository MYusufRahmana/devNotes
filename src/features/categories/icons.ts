import {
  Atom,
  BookOpen,
  Box,
  Cloud,
  Code,
  Container,
  Cpu,
  Database,
  Flame,
  Folder,
  GitBranch,
  Globe,
  Hash,
  KeyRound,
  Layers,
  Monitor,
  Network,
  Package,
  Rocket,
  Server,
  Shield,
  Smartphone,
  Terminal,
  Wrench,
  Zap,
  type LucideIcon,
} from 'lucide-react'

export const CATEGORY_ICONS: Record<string, LucideIcon> = {
  hash: Hash,
  'git-branch': GitBranch,
  atom: Atom,
  flame: Flame,
  container: Container,
  database: Database,
  network: Network,
  terminal: Terminal,
  monitor: Monitor,
  zap: Zap,
  wrench: Wrench,
  server: Server,
  cloud: Cloud,
  code: Code,
  globe: Globe,
  shield: Shield,
  key: KeyRound,
  box: Box,
  package: Package,
  layers: Layers,
  cpu: Cpu,
  rocket: Rocket,
  smartphone: Smartphone,
  book: BookOpen,
  folder: Folder,
}

export function categoryIcon(name: string | null | undefined): LucideIcon {
  return (name && CATEGORY_ICONS[name]) || Hash
}
